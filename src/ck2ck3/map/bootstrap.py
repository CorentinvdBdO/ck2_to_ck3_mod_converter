"""Throwaway CK3 scaffolding so the physical map can be loaded in game.

**Everything in this module is placeholder content that the ``titles-history``
lane replaces.**  It exists for one reason: CK3 will not boot a custom map
without a title layer over it, and a map that cannot be booted cannot be
checked.  Every file it writes carries a THROWAWAY banner.

Design notes and the evidence behind them are in ``docs/output_bootstrap.md``:

* ``descriptor.mod``, not ``.metadata/metadata.json`` — none of Atlantis,
  Elder Kings 2 or Godherja ships a metadata dir, and ck3-tiger cannot read one.
* ``replace_path`` replaces one directory and **not** its subdirectories, so
  ``map_data`` itself needs no replace_path (same-filename override is enough,
  the Elder Kings 2 / Godherja pattern) while
  ``map_data/geographical_regions`` does need one.
* one barony per province, named from the CK2 ``definition.csv`` name, because
  this lane is explicitly one CK3 province per CK2 province.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from .idmap import Ck3Province

THROWAWAY = (
    "# THROWAWAY SCAFFOLDING generated by ck2ck3 lane map-physical.\n"
    "# One barony per CK2 province, no real de-jure structure, no history.\n"
    "# The titles-history lane replaces this file wholesale. Do not build on it.\n"
)

#: directories our generated mod must replace rather than merge into vanilla.
#: `verified` from the ck3-tiger binary's own help text: "replace_path only
#: replaces the specific directory, not any directories below it".
REPLACE_PATHS = (
    "common/landed_titles",
    "history/characters",
    "history/cultures",
    "history/province_mapping",
    "history/provinces",
    "history/struggles",
    "history/titles",
    "history/wars",
    "map_data/geographical_regions",
)


def slugify(name: str, fallback: str) -> str:
    """CK3 title keys are ``[a-z0-9_]``; CK2 province names are free text."""
    s = name.lower()
    s = s.replace("'", "").replace("’", "")
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or fallback


def definition_names(
    provinces: Sequence[Ck3Province], keys: dict[int, str]
) -> dict[int, str]:
    """CK3 province id -> the identifier that goes in definition.csv column 5.

    **This column is the contract with the ``titles-history`` lane**: for a
    barony province it is the CK3 barony title id, ``b_<ck2 barony name>``,
    verbatim from CK2 ``landed_titles``, so the titles lane can read a province
    id straight out of ``definition.csv`` instead of guessing one.

    For everything else — sea, lake, river, impassable, and land the CK2 mod
    gave no county — it stays what lane ``map-physical`` made it: the uppercase
    slug of the CK2 province name.  Vanilla writes an uppercase identifier
    there (``VESTFIRDIR``, ``REYKJAVIK``), not a display name, and ck3-tiger
    reads the column as a localisation key; Faerûn's CK2 names have spaces and
    apostrophes, so writing them raw produced 2600 "missing localization key
    Trackless Sea" warnings and then 1092 .yml parse warnings.  Every value
    this function returns gets a localisation entry (see
    :func:`localisation_entries`).
    """
    by_id = {p.id: p for p in provinces}
    out: dict[int, str] = {}
    for pid, slug in keys.items():
        p = by_id.get(pid)
        out[pid] = p.barony if (p is not None and p.barony) else slug.upper()
    return out


def unique_keys(provinces: Sequence[Ck3Province]) -> dict[int, str]:
    """CK3 province id -> unique title-key stem, suffixed on collision.

    A barony province's stem is its **CK2 barony key minus the ``b_``**, so the
    generated title is the CK2 title (`verified`: Faerûn declares 15,356
    baronies and no key twice).  Everything else keeps the slug of its CK2
    province name, as lane ``map-physical`` had it.
    """
    out: dict[int, str] = {}
    used: dict[str, int] = {}
    for p in provinces:
        if p.barony:
            base = p.barony[2:] if p.barony.startswith("b_") else p.barony
        else:
            base = slugify(p.name, f"province_{p.id}")
        n = used.get(base, 0)
        used[base] = n + 1
        out[p.id] = base if n == 0 else f"{base}_{n + 1}"
    return out


@dataclass(frozen=True)
class BootstrapDefaults:
    """Vanilla ids used as placeholders so the game has something valid to load."""

    #: `verified` in CK3 1.19: culture `norse` is in
    #: common/culture/cultures/00_north_germanic.txt, faith `norse_pagan` is in
    #: common/religion/religion_types/00_germanic.txt. NOTE 1.19 renamed
    #: common/religion/religions/ to common/religion/religion_types/, and there
    #: is no faith called `asatru` any more - that was the first guess and
    #: ck3-tiger rejected it 2335 times.
    culture: str = "norse"
    faith: str = "norse_pagan"
    holding: str = "castle_holding"


#: CK3 world-extent defines. NOT throwaway — a custom map size is wrong
#: without these, and the symptom is a silently misplaced coastline.
#:
#: `verified` in game/common/defines/00_defines.txt:74-77 (vanilla 9216x4608),
#: Elder Kings 2 common/defines/ek_defines.txt:34-37 (8256x5504) and Godherja
#: common/defines/00_defines.txt:79-82 (8192x4096):
#:   WORLD_EXTENTS_X = provinces.png width  - 1
#:   WORLD_EXTENTS_Z = provinces.png height - 1
#:   WORLD_EXTENTS_Y = vertical world extent in game units (50 vanilla, 51 both TCs)
#:   WATERLEVEL      = water surface in the same units (3 vanilla, 3.8 both TCs)
#:
#: and the 16-bit heightmap value of the water surface follows:
#:   water = WATERLEVEL / WORLD_EXTENTS_Y * 65535
#: vanilla 3/50*65535 = 3932, both TCs 3.8/51*65535 = 4883, which is exactly the
#: value measured off their coastlines (docs/formats_map.md §3).
WORLD_EXTENTS_Y = 51
WATERLEVEL = 3.8


def water_level_16bit(
    *, waterlevel: float = WATERLEVEL, extents_y: float = WORLD_EXTENTS_Y
) -> int:
    """The 16-bit ``heightmap.png`` value of the water surface."""
    return int(round(waterlevel / extents_y * 65535))


def render_defines(
    *,
    width: int,
    height: int,
    extents_y: float = WORLD_EXTENTS_Y,
    waterlevel: float = WATERLEVEL,
) -> str:
    """``common/defines/<prefix>_defines.txt`` — the map's world extents."""
    return (
        "# GENERATED by ck2ck3 (lane map-physical). Do not hand-edit.\n"
        "# World extents must match provinces.png or the coastline moves:\n"
        "#   WORLD_EXTENTS_X = width - 1, WORLD_EXTENTS_Z = height - 1.\n"
        f"# Water surface in heightmap.png is {water_level_16bit(waterlevel=waterlevel, extents_y=extents_y)}"
        f" = {waterlevel} / {extents_y} * 65535.\n"
        "NJominiMap = {\n"
        f"\tWORLD_EXTENTS_X = {width - 1}\n"
        f"\tWORLD_EXTENTS_Y = {extents_y}\n"
        f"\tWORLD_EXTENTS_Z = {height - 1}\n"
        f"\tWATERLEVEL = {waterlevel}\n"
        "}\n"
    )


def render_camera_defines(*, width: int, height: int) -> str:
    """The ``NCamera`` block a non-vanilla canvas needs.

    ``PANNING_WIDTH`` / ``PANNING_HEIGHT`` are the camera's bound, in the same
    bottom-up pixel frame as the locators.  There is no ``MAX_ZOOM`` and no
    ``MAP_BOUNDS``; these two are it.  Vanilla ships ``9090`` / ``4696``
    (``game/common/defines/graphic/00_graphics.txt:193-194``), so on our taller
    sheet the north of the map is simply unreachable — 2088 px of 6784 on the
    Faerûn build.

    Elder Kings 2 sets both to its canvas exactly
    (``common/defines/graphic/ek_graphics.txt:13-14``, 8256x5504) and Godherja
    sets the height to its canvas (``.../00_graphics.txt:194``).  Neither
    touches ``ZOOM_STEPS``, ``FOV`` or the ``MAPTABLE_*`` levels, so a non-2:1
    aspect needs nothing else here.

    ``START_LOOK_AT`` is in the same frame and has to move too, or the game
    opens looking at wherever vanilla's Mediterranean was.

    Written to ``common/defines/graphic/<prefix>_graphics.txt``, not next to
    ``NJominiMap``: that is where vanilla and both TCs keep ``NCamera``.
    """
    return (
        "# GENERATED by ck2ck3 (lane map-ui). Do not hand-edit.\n"
        "# Camera bounds follow the canvas, or the far edge is unreachable:\n"
        "# vanilla ships PANNING_WIDTH 9090 / PANNING_HEIGHT 4696 for 9216x4608\n"
        "# (game/common/defines/graphic/00_graphics.txt:193-194) and Elder Kings 2\n"
        "# sets both to its own canvas (ek_graphics.txt:13-14). There is no\n"
        "# MAX_ZOOM and no MAP_BOUNDS. See docs/evidence/map_ui_research.md §2.\n"
        "NCamera = {\n"
        f"\tPANNING_WIDTH = {width}\n"
        f"\tPANNING_HEIGHT = {height}\n"
        f"\tSTART_LOOK_AT = {{ {width / 2:.1f} 0 {height / 2:.1f} }}\n"
        "}\n"
    )


# NOTE: descriptor.mod is NOT written here. The `descriptor` step owns it
# (docs/cli.md) and takes its replace_path list from `mod.replace_paths` in the
# CLI config, so REPLACE_PATHS below has to be mirrored there. The standalone
# entry point writes it via render_descriptor().


def render_descriptor(*, name: str, version: str, supported_version: str) -> str:
    """descriptor.mod, for the standalone entry point only."""
    out = [f'version="{version}"']
    out += [f'replace_path="{rel}"' for rel in REPLACE_PATHS]
    out += [
        "tags={",
        '\t"Total Conversion"',
        '\t"Map"',
        "}",
        f'name="{name}"',
        f'supported_version="{supported_version}"',
    ]
    return "\n".join(out) + "\n"



def render_landed_titles(
    provinces: Sequence[Ck3Province],
    keys: dict[int, str],
    *,
    empire_key: str = "e_placeholder",
    kingdom_key: str = "k_placeholder",
    duchy_key: str = "d_placeholder",
) -> tuple[str, int]:
    """One county per CK2 county, its built baronies inside it, one kingdom.

    Grouping by the real CK2 duchies is deliberately *not* done here: the CK2
    duchy layer lives in ``common/landed_titles`` on the CK2 side and porting it
    is the titles-history lane's whole job.  A flat single-kingdom tree is the
    cheapest thing CK3 accepts, and it keeps this file obviously throwaway.

    What *is* real is the county -> barony grouping, because the map depends on
    it: several provinces now share a county, and a barony province with no
    county over it is a hole in the map.  Land the CK2 mod gave no county
    (Faerûn's 213 wasteland provinces) gets a one-barony county of its own.
    """
    land = [p for p in provinces if not p.is_water and not p.is_impassable]
    counties: dict[str, list[Ck3Province]] = {}
    for p in land:
        counties.setdefault(p.county or f"c_{keys[p.id]}", []).append(p)

    out = [THROWAWAY, "", f"{empire_key} = {{", "\tcolor = { 120 120 160 }", ""]
    out += [f"\t{kingdom_key} = {{", "\t\tcolor = { 130 130 170 }", ""]
    out += [f"\t\t{duchy_key} = {{", "\t\t\tcolor = { 140 140 180 }", ""]
    for county, members in counties.items():
        seat = members[0]
        out += [
            f"\t\t\t{county} = {{",
            "\t\t\t\tcolor = { %d %d %d }" % seat.rgb,
        ]
        for p in members:
            out += [
                f"\t\t\t\tb_{keys[p.id]} = {{",
                "\t\t\t\t\tcolor = { %d %d %d }" % p.rgb,
                f"\t\t\t\t\tprovince = {p.id}",
                "\t\t\t\t}",
            ]
        out += ["\t\t\t}"]
    out += ["\t\t}", "\t}", "}"]
    return "\n".join(out) + "\n", len(land)


def render_province_history(
    provinces: Sequence[Ck3Province],
    defaults: BootstrapDefaults = BootstrapDefaults(),
) -> tuple[str, int]:
    """``history/provinces/<prefix>_provinces.txt``.

    CK3 needs a culture and a faith on every land province or the province is
    unsettled and the map shows holes.  Vanilla ids are used on purpose: the
    cultures-religions lane has not run, and inventing a culture here would
    break the no-invention rule.
    """
    land = [p for p in provinces if not p.is_water and not p.is_impassable]
    out = [
        THROWAWAY,
        f"# Placeholder culture/faith are the vanilla ids {defaults.culture!r} /"
        f" {defaults.faith!r}; the cultures-religions lane replaces them.",
        "# The `holding` line is NOT placeholder: it is the CK3 equivalent of the",
        "# CK2 holding actually built in history/provinces (docs/step_map_baronies.md).",
        "",
    ]
    for p in land:
        out += [
            f"{p.id} = {{",
            f"\tculture = {defaults.culture}",
            f"\tfaith = {defaults.faith}",
            f"\tholding = {p.holding or defaults.holding}",
            "}",
        ]
    return "\n".join(out) + "\n", len(land)


def render_title_history(*, kingdom_key: str = "k_placeholder") -> str:
    """``history/titles/`` — empty is valid; the dir must exist for replace_path."""
    return THROWAWAY + f"# No title holders yet; {kingdom_key} starts unheld.\n"


#: Localisation keys that must NOT be emitted because CK3 hashes keys with
#: MURMUR3A and these collide with a vanilla key, which is a hard ck3-tiger
#: error rather than a warning:
#:   b_lonefang_adj  vs  court.6070.b  (hash 0x89D63247)
#:
#: A deny-list is the honest fix here only because this file is throwaway
#: scaffolding. The titles-history lane emits real titles and needs a proper
#: check: hash every generated key with MURMUR3A and compare against the vanilla
#: key set. Treat this constant as a reminder, not a pattern to copy.
LOC_KEY_COLLISIONS = frozenset({"b_lonefang_adj"})


#: replaced directories this lane fills with real content, so they get no banner
HAS_REAL_CONTENT = frozenset(
    {
        "common/landed_titles",
        "history/provinces",
        "history/titles",
        "map_data/geographical_regions",
    }
)


#: Filename of the banner dropped in each replaced directory. NOT `.txt`:
#: CK3 reads the *filename* in some history folders as an identifier, so a
#: `history/cultures/zz_emptied_by_converter.txt` made the game look for a
#: culture called `zz_emptied_by_converter` (`verified`, ck3-tiger
#: "culture zz_emptied_by_converter not defined"). A `.md` is ignored by the
#: game and still keeps the directory alive in git.
EMPTY_MARKER = "zz_emptied_by_converter.md"


def render_empty_replacements(
    skip: frozenset[str] = HAS_REAL_CONTENT,
) -> dict[str, str]:
    """One banner file in each replaced directory so the dir is not empty.

    A ``replace_path`` on a directory that does not exist in the mod is what
    actually neutralises vanilla content, but an empty directory does not
    survive git, so each gets a comment-only file.
    """
    out: dict[str, str] = {}
    for rel in REPLACE_PATHS:
        if rel in skip:
            continue  # this lane writes real content there
        out[f"{rel}/{EMPTY_MARKER}"] = (
            THROWAWAY
            + f"# {rel} is replace_path'd so vanilla content here is dropped:\n"
            "# it references vanilla province ids that do not exist on this map.\n"
        )
    return out


def humanise(key: str) -> str:
    """``b_castle_waterdeep`` -> ``Castle Waterdeep``, for an unlocalised title.

    Only used when the CK2 mod has no localisation for the key. It is a
    presentation fallback, not invented content: the words are the CK2 id's own.
    """
    stem = key.split("_", 1)[1] if key[:2] in ("b_", "c_", "d_", "k_", "e_") else key
    return " ".join(w.capitalize() for w in stem.split("_")) or key


def localisation_entries(
    provinces: Sequence[Ck3Province],
    keys: dict[int, str],
    *,
    loc_names: dict[str, str] | None = None,
) -> dict[str, str]:
    """Localisation keys for the generated titles and definition.csv names.

    Returned as a dict, not a file, so the caller writes them with
    ``ctx.write_loc`` -- which owns the UTF-8 BOM, the CRLF line endings and
    the ``l_english:`` first line that CK3 requires.

    ``loc_names`` is the CK2 barony localisation (``b_x -> "Castle Waterdeep"``);
    a barony that has it keeps its CK2 name, so the generated map reads in
    Faerûnian rather than in slugs.  A barony without it falls back to
    :func:`humanise` of its own id.
    """
    names = loc_names or {}
    out: dict[str, str] = {}
    for p in provinces:
        # A province NAME needs a key even for water and impassable provinces:
        # ck3-tiger reads map_data/definition.csv column 5 as a localisation key
        # and warns for every one that is missing, which was 2600 warnings from
        # the sea provinces alone ("Trackless Sea", "Crowded Sea", ...).
        if p.barony:
            out.setdefault(p.barony, names.get(p.barony) or humanise(p.barony))
        else:
            out.setdefault(keys[p.id].upper(), p.name or keys[p.id])
        if p.is_water or p.is_impassable:
            continue
        barony_key = f"b_{keys[p.id]}"
        out[barony_key] = (
            names.get(p.barony or "") or (p.name if not p.barony else "")
            or humanise(barony_key)
        )
        county = p.county or f"c_{keys[p.id]}"
        out.setdefault(county, names.get(county) or humanise(county))
    for tier, label in (("e", "Empire"), ("k", "Kingdom"), ("d", "Duchy")):
        out[f"{tier}_placeholder"] = f"Converter Placeholder {label}"
        out[f"{tier}_placeholder_adj"] = f"Converter Placeholder {label}"
    for key in [k for k in out if k.startswith(("c_", "b_"))]:
        adj = f"{key}_adj"
        if adj not in LOC_KEY_COLLISIONS and adj not in out:
            out[adj] = out[key]
    return out
