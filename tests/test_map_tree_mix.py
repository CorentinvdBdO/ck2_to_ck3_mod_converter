"""Regional tree mix: P(mesh | terrain, climate, latitude band).

`docs/step_map_paint.md` §9.9. The sampler must be deterministic across
processes, coherent at the stand scale, faithful to the measured conditional
table, and must not change the density contract §9.2 fixed (how many trees
and where) — only which mesh each one gets.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from ck2ck3.map import tree_scatter

REPO = Path(__file__).resolve().parents[1]

PINE = "tree_pine_01_b_generator_1.txt"
LEAF = "tree_leaf_high_generator_1.txt"
PALM = "tree_palm_generator_1.txt"


def _mix_csv(tmp_path: Path, body: str, name: str = "tree_mix.csv") -> Path:
    p = tmp_path / name
    p.write_text(
        "# GENERATED by a test, and a comment line every reader must skip\n"
        "ck3_terrain,climate,lat_band,file,count,p\n" + body,
        encoding="utf-8",
    )
    return p


# --------------------------------------------------------------- the table


def test_read_mix_table_skips_comments_and_normalises(tmp_path):
    path = _mix_csv(
        tmp_path,
        f"forest,severe,0,{PINE},30,0.75\n"
        f"forest,severe,0,{LEAF},10,0.25\n"
        # a hand-trimmed condition whose shares no longer sum to 1
        f"forest,none,*,{LEAF},10,0.4\n",
    )
    table = tree_scatter.read_mix_table(path)
    assert table[("forest", "severe", "0")].files == (LEAF, PINE)
    assert table[("forest", "severe", "0")].cdf == (0.25, 1.0)
    assert table[("forest", "none", "*")].cdf == (1.0,)


def test_read_mix_table_missing_file_is_empty_not_an_error(tmp_path):
    assert tree_scatter.read_mix_table(tmp_path / "nope.csv") == {}


def test_resolve_mix_tries_latitude_before_climate():
    """Measured, not assumed: over vanilla's own 549,126 instances the
    latitude band explains far more of the species choice than the climate
    zone (docs/evidence/vanilla_tree_mix_conditioning.csv, 1.626 vs 2.008
    bits of cross-entropy against terrain alone at 2.056)."""
    d_full = tree_scatter.MixDist((PINE,), (1.0,))
    d_clim = tree_scatter.MixDist((LEAF,), (1.0,))
    d_band = tree_scatter.MixDist((PALM,), (1.0,))
    d_terr = tree_scatter.MixDist(("reeds_01_generator_1.txt",), (1.0,))
    table = {
        ("forest", "severe", "0"): d_full,
        ("forest", "severe", "*"): d_clim,
        ("forest", "*", "0"): d_band,
        ("forest", "*", "*"): d_terr,
    }
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (
        d_full, "terrain+climate+band")
    del table[("forest", "severe", "0")]
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (
        d_band, "terrain+band")
    del table[("forest", "*", "0")]
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (
        d_clim, "terrain+climate")
    # ...but a neighbouring band beats the climate marginal: bands are
    # ordinal and vanilla has no forest at all in its own band 0
    table[("forest", "*", "1")] = d_band
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (
        d_band, "terrain+neighbour_band")
    del table[("forest", "*", "1")]
    del table[("forest", "severe", "*")]
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (
        d_terr, "terrain")
    del table[("forest", "*", "*")]
    assert tree_scatter.resolve_mix(table, "forest", "severe", 0) == (None, "none")


def test_apply_mix_overrides_replaces_a_condition_and_leaves_the_rest(tmp_path):
    table = tree_scatter.read_mix_table(
        _mix_csv(tmp_path, f"drylands,none,9,{LEAF},99,1.0\n"
                           f"forest,none,0,{PINE},99,1.0\n")
    )
    overrides = tree_scatter.read_mix_table(
        _mix_csv(tmp_path, f"drylands,none,9,{PALM},,1\n", name="ov.csv")
    )
    merged = tree_scatter.apply_mix_overrides(table, overrides)
    assert merged[("drylands", "none", "9")].files == (PALM,)
    assert merged[("forest", "none", "0")].files == (PINE,)


# ------------------------------------------------------------- the sampler


def _points(n: int, x0: float = 0.0, y0: float = 0.0, spread: float = 1.0):
    xs = x0 + (np.arange(n) % 8) * spread
    ys = y0 + (np.arange(n) // 8) * spread
    return xs.astype(float), ys.astype(float)


def test_sampler_is_deterministic():
    xs, ys = _points(400, spread=7.0)
    args = dict(
        table={("forest", "none", "0"): tree_scatter.MixDist(
            (LEAF, PINE), (0.5, 1.0))},
        mesh_of_terrain={"forest": LEAF},
        cell_px=24,
        seed=99,
        coherence=0.5,
    )
    t = np.array(["forest"] * 400, dtype=object)
    c = np.array(["none"] * 400, dtype=object)
    b = np.zeros(400, dtype=int)
    a1, f1, _ = tree_scatter.assign_regional_meshes(xs, ys, t, c, b, **args)
    a2, f2, _ = tree_scatter.assign_regional_meshes(xs, ys, t, c, b, **args)
    assert f1 == f2
    assert np.array_equal(a1, a2)


def test_cell_uniform_is_stable_across_processes():
    """crc32, never hash(): the yaw seed already cost 1.4 M diff lines."""
    import subprocess
    import sys

    v = tree_scatter.cell_uniform(np.array([3, 3, 4]), np.array([7, 7, 7]), 4242)
    assert v[0] == v[1] and v[0] != v[2]
    assert 0.0 <= v[0] < 1.0
    code = (
        "import numpy as np;"
        "from ck2ck3.map.tree_scatter import cell_uniform;"
        "print(cell_uniform(np.array([3]), np.array([7]), 4242)[0])"
    )
    outs = {
        subprocess.run(
            [sys.executable, "-c", code],
            env={"PYTHONHASHSEED": str(i), "PYTHONPATH": "src"},
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        for i in (1, 2)
    }
    assert len(outs) == 1
    assert float(outs.pop()) == pytest.approx(v[0])


def test_full_coherence_makes_one_cell_one_species():
    """Vanilla's species form stands; per-pixel salt and pepper is the bug."""
    # 64 points inside a single 24 px cell, all the same condition
    xs = np.linspace(0.5, 23.5, 64)
    ys = np.full(64, 5.0)
    t = np.array(["forest"] * 64, dtype=object)
    c = np.array(["none"] * 64, dtype=object)
    b = np.zeros(64, dtype=int)
    ids, files, _ = tree_scatter.assign_regional_meshes(
        xs, ys, t, c, b,
        {("forest", "none", "0"): tree_scatter.MixDist((LEAF, PINE), (0.5, 1.0))},
        {"forest": LEAF},
        cell_px=24, seed=1, coherence=1.0,
    )
    assert len(set(ids.tolist())) == 1
    # ...and a different cell can differ: 256 cells cannot all agree
    xs2 = np.arange(256) * 24.0 + 1.0
    ys2 = np.full(256, 5.0)
    ids2, _f, _l = tree_scatter.assign_regional_meshes(
        xs2, ys2, np.array(["forest"] * 256, dtype=object),
        np.array(["none"] * 256, dtype=object), np.zeros(256, dtype=int),
        {("forest", "none", "0"): tree_scatter.MixDist((LEAF, PINE), (0.5, 1.0))},
        {"forest": LEAF},
        cell_px=24, seed=1, coherence=1.0,
    )
    assert len(set(ids2.tolist())) == 2


