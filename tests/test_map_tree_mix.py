# ------------------------------------------------------- the whole scatter


def _grid(shape, keys, key):
    return np.full(shape, keys.index(key), dtype=np.uint8)


def test_regional_scatter_places_the_same_points_as_the_terrain_only_one():
    """Density contract: only the *which mesh* step changes (§9.2)."""
    eligible = np.zeros((60, 60), dtype=bool)
    eligible[10:50, 10:50] = True
    tkeys = ["forest"]
    ckeys = ["severe"]
    tcode = _grid(eligible.shape, tkeys, "forest")
    ccode = _grid(eligible.shape, ckeys, "severe")
    mesh = {"forest": LEAF}
    plain, d0, _dbt = tree_scatter.scatter(
        eligible, tcode, tkeys, mesh, target_total=500, seed=3
    )
    reg, d1, _dbt2, _lv = tree_scatter.scatter_regional(
        eligible, tcode, tkeys, ccode, ckeys, mesh,
        {("forest", "severe", "*"): tree_scatter.MixDist((PINE,), (1.0,))},
        canvas_height=60, target_total=500, seed=3,
    )
    assert d0 == d1 == 0
    assert sum(v.shape[0] for v in plain.values()) == 500
    assert sum(v.shape[0] for v in reg.values()) == 500
    assert set(plain) == {LEAF} and set(reg) == {PINE}
    assert np.array_equal(
        np.sort(plain[LEAF], axis=0), np.sort(reg[PINE], axis=0)
    )


def _fake_game_dir(tmp_path: Path, files: list[str]) -> Path:
    d = tmp_path / "game" / tree_scatter.GENERATED_DIR
    d.mkdir(parents=True)
    for i, f in enumerate(files):
        (d / f).write_text(
            "object={\n"
            f'\tname="{f[:-4]}_0"\n'
            "\trender_pass=Map\n"
            "\tclamp_to_water_level=no\n"
            "\tgenerated_content=yes\n"
            '\tlayer="tree_high_layer"\n'
            f'\tpdxmesh="mesh_{i}"\n'
            "\tcount=1\n"
            '\ttransform="1 0 1 0 0 0 1 1 1 1"\n'
            "}\n",
            encoding="utf-8",
        )
    return tmp_path / "game"


def test_render_all_stubs_every_generator_the_mix_never_uses(tmp_path):
    """All 18 vanilla files stay overridden; an unused one is an honest
    empty stub, never a fabricated block (§9.2)."""
    all_files = [PINE, LEAF, PALM, "tree_sakura_01_generator.txt"]
    game = _fake_game_dir(tmp_path, all_files)
    mesh_csv = tmp_path / "tree_meshes.csv"
    mesh_csv.write_text(
        f"ck3_terrain,file,note\nforest,{LEAF},x\n", encoding="utf-8"
    )
    eligible = np.ones((20, 20), dtype=bool)
    tkeys, ckeys = ["forest"], ["severe"]
    out, counts, dropped, _by_t, levels = tree_scatter.render_all(
        game,
        mesh_csv,
        eligible,
        _grid(eligible.shape, tkeys, "forest"),
        tkeys,
        20,
        target_total=100,
        seed=7,
        mix_table={("forest", "severe", "*"): tree_scatter.MixDist(
            (PINE,), (1.0,))},
        climate_code=_grid(eligible.shape, ckeys, "severe"),
        climate_keys=ckeys,
    )
    assert set(out) == {
        f"{tree_scatter.GENERATED_DIR}/{f}" for f in all_files
    }
    assert counts == {PINE: 100}
    assert dropped == 0
    assert levels == {"terrain+climate": 100}
    for f in (LEAF, PALM, "tree_sakura_01_generator.txt"):
        assert "instances={\n\t}\n" in out[f"{tree_scatter.GENERATED_DIR}/{f}"]
    assert "count=100\n" in out[f"{tree_scatter.GENERATED_DIR}/{PINE}"]


