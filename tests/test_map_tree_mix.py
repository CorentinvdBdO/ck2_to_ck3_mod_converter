def test_shipped_mix_csv_is_well_formed_and_names_real_generators():
    table = tree_scatter.read_mix_table(REPO / "mappings" / "tree_mix.csv")
    assert len(table) > 100, "mappings/tree_mix.csv looks empty"
    mesh = tree_scatter.read_mesh_table(REPO / "mappings" / "tree_meshes.csv")
    for key, dist in table.items():
        assert dist.cdf[-1] == pytest.approx(1.0)
        assert list(dist.cdf) == sorted(dist.cdf)
        assert key[1] == tree_scatter.MIX_WILDCARD or key[1] in {
            "none", "mild", "normal", "severe"
        }
    # every terrain our own art table plants trees on resolves to something
    for terrain, f in mesh.items():
        if not f:
            continue
        dist, _level = tree_scatter.resolve_mix(table, terrain, "none", 5)
        assert dist is not None, f"no mix row reachable for terrain {terrain}"


def test_mix_csv_bands_match_the_sampler():
    """The table's band count and `tree_scatter.N_LAT_BANDS` must agree —
    they are written by two different programs."""
    import csv

    path = REPO / "mappings" / "tree_mix.csv"
    with path.open("r", encoding="utf-8", newline="") as fh:
        rows = list(
            csv.DictReader(line for line in fh if not line.lstrip().startswith("#"))
        )
    bands = {
        int(r["lat_band"])
        for r in rows
        if r["lat_band"] != tree_scatter.MIX_WILDCARD
    }
    assert bands == set(range(tree_scatter.N_LAT_BANDS))


def test_cli_config_builder_reads_the_tree_keys():
    """A `[map] trees*` key the REAL CLI builder never reads is a silent
    no-op — the `[map] colormap = false` bug, twice over."""
    from ck2ck3.steps import map as map_step

    class Cfg:
        raw = {"map": {"vanilla_km_per_px": 1.0, "source_km_per_px": 1.0,
                       "trees": False,
                       "trees_regional": False,
                       "trees_seed": 7,
                       "trees_cell_px": 99,
                       "trees_cell_coherence": 0.25,
                       "trees_mix_csv": "mappings/other.csv"}}
        path = Path("configs/x.toml")
        out = Path("/tmp/out")
        prefix = "fae"
        bookmark_date = (1357, 1, 1)
        name = "n"
        version = "0"
        supported_version = "1.19.*"

    class Ctx:
        config = Cfg()

        def ck2(self, *parts):
            return Path("/tmp/ck2").joinpath(*parts)

        def ck3(self, *parts):
            return Path("/tmp/ck3").joinpath(*parts)

    cfg = map_step._map_config(Ctx())
    assert cfg.trees is False
    assert cfg.trees_regional is False
    assert cfg.trees_seed == 7
    assert cfg.trees_cell_px == 99
    assert cfg.trees_cell_coherence == 0.25
    assert cfg.trees_mix_csv == Path("mappings/other.csv")
    for k in ("trees", "trees_regional", "trees_seed", "trees_cell_px",
              "trees_cell_coherence", "trees_mix_csv"):
        Cfg.raw["map"].pop(k)
    cfg = map_step._map_config(Ctx())
    assert cfg.trees is True
    assert cfg.trees_regional is True
    assert cfg.trees_seed == 4242
    assert cfg.trees_cell_px == 24
    assert cfg.trees_mix_csv == Path("mappings/tree_mix.csv")
    assert cfg.trees_mix_overrides_csv == Path("overrides/tree_mix.csv")
    assert cfg.trees_csv == Path("mappings/tree_meshes.csv")


